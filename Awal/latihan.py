# Membuat program menghitung luas persegi panjang
# Input data
panjang = 10;
lebar = 100;
luas = panjang * lebar;

print("Luas persegi panjang dari hal yang diketahui dibawah adalah")

# Proses Output
print(f"Panjang = {panjang} cm")
print(f"Lebar = {lebar} cm")
print(f"Luas = {luas} cm^2")

# Membuat program menghitung luas segitiga yang nilainya ditentukan
# Input data
alas = 20;
tinggi = 90;
luas = 0.5 * alas * tinggi

print("Luas segitiga dari hal yang diketahui dibawah adalah")

# Proses Output
print(f"Alas Segitiga = {alas} cm")
print(f"Tinggi Segitga = {tinggi} cm")
print(f"Luas Segitga = {luas} cm^2")
